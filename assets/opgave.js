// Interactive Python exercise: editor + parameter sliders + run + output.
//
// In a page (.qmd), an exercise is a div that names its code file:
//
//   ::: {.opgave code="bisectie_bal.py"}
//   ```{.parameters}
//   a   : -10 .. 30 step 0.5        # linkergrens
//   eps : 0.1 | 0.01 | 0.001 | 0    # stopcriterium
//   p0  : text                      # startwaarden
//   ```
//   :::
//
// Parameter lines are optional. A parameter is a value in the code itself:
// the right-hand side of `name = ...` or the list in `for name in ...:`.
// Moving a slider rewrites that value in the code (so the student sees what
// changed) and runs the program again; editing the code moves the slider.
//
//   name : min .. max step s   slider over a range
//   name : v1 | v2 | v3        slider over fixed choices, written as in the code
//   name : text                text box (e.g. a list of start values)
//
// The code is fetched from code/<file>, the booklet output (if any) from
// code/output/<name>.txt, generated by scripts/uitvoer_boekje.py.

import {
  EditorState, EditorView, keymap, lineNumbers, highlightActiveLine,
  highlightActiveLineGutter, drawSelection, defaultKeymap, history,
  historyKeymap, indentWithTab, indentOnInput, bracketMatching,
  syntaxHighlighting, HighlightStyle, indentUnit, python, tags,
} from "./vendor/codemirror.js";

const TIME_LIMIT_S = 10;
const MAX_LINES = 2000;
const STORAGE_PREFIX = "numwis:";

// ---------------------------------------------------------------- Python --

// One worker per page, shared by all exercises on it. It is replaced by a
// fresh one when a program has to be stopped.
const runtime = {
  worker: null,
  ready: false,
  version: "",
  owner: null, // the exercise whose program is running
  listeners: new Set(), // exercise widgets, told about every state change
  onMessage: null, // the running exercise's handler

  start() {
    this.ready = false;
    this.worker = new Worker(new URL("python-worker.js", import.meta.url), { type: "module" });
    this.worker.onerror = (event) => {
      event.preventDefault();
      this.notify(event.message || "downloaden mislukt");
    };
    this.worker.onmessage = ({ data }) => {
      if (data.type === "ready") {
        this.ready = true;
        this.version = data.python;
        this.notify();
      } else if (data.type === "fatal") {
        this.notify(data.message);
      } else {
        this.onMessage?.(data);
      }
    };
    this.notify();
  },

  restart() {
    this.worker.terminate();
    this.start();
  },

  notify(error) {
    for (const widget of this.listeners) widget.pythonChanged(error);
  },
};

// -------------------------------------------------------------- helpers --

const el = (tag, attrs = {}, ...children) => {
  const node = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs)) {
    if (key === "class") node.className = value;
    else if (key.startsWith("on")) node.addEventListener(key.slice(2), value);
    else node.setAttribute(key, value);
  }
  node.append(...children);
  return node;
};

const storage = {
  get(key) {
    try { return JSON.parse(localStorage.getItem(STORAGE_PREFIX + key)); } catch { return null; }
  },
  set(key, value) {
    try { localStorage.setItem(STORAGE_PREFIX + key, JSON.stringify(value)); } catch {}
  },
  remove(key) {
    try { localStorage.removeItem(STORAGE_PREFIX + key); } catch {}
  },
};

const seconds = (s) => (s < 0.1 ? "< 0,1 s" : `${s.toFixed(1).replace(".", ",")} s`);
const sameText = (a, b) => a.trimEnd().replace(/\r\n/g, "\n") === b.trimEnd().replace(/\r\n/g, "\n");
// 0.5000 -> "0.5", 10 -> "10.0" (stays a float in Python), unless the step is whole
const formatNumber = (x, decimals) =>
  decimals === 0 ? x.toFixed(0) : x.toFixed(decimals).replace(/0+$/, "").replace(/\.$/, ".0");
const escapeRegExp = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// Share links carry the code in the URL fragment: #code=<base64url(deflate)>
async function encodeCode(code) {
  const stream = new Blob([code]).stream().pipeThrough(new CompressionStream("deflate-raw"));
  const bytes = new Uint8Array(await new Response(stream).arrayBuffer());
  return btoa(String.fromCharCode(...bytes)).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

async function decodeCode(text) {
  const b64 = text.replace(/-/g, "+").replace(/_/g, "/");
  const bytes = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
  const stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream("deflate-raw"));
  return new Response(stream).text();
}

// ------------------------------------------------------------ parameters --

function parseParameters(text) {
  const params = [];
  for (const raw of text.split("\n")) {
    const [spec, ...help] = raw.split("#");
    const match = spec.match(/^\s*([A-Za-z_]\w*)\s*:\s*(.+?)\s*$/);
    if (!match) continue;
    const [, name, kind] = match;
    const param = { name, help: help.join("#").trim() };
    const range = kind.match(/^(\S+)\s*\.\.\s*(\S+)\s+step\s+(\S+)$/);
    if (range) {
      Object.assign(param, { type: "range", min: +range[1], max: +range[2], step: +range[3] });
      param.decimals = (range[3].split(".")[1] ?? "").length;
    } else if (kind === "text") {
      param.type = "text";
    } else {
      param.type = "choice";
      param.choices = kind.split("|").map((s) => s.trim());
    }
    params.push(param);
  }
  return params;
}

// Where in the code a parameter's value sits: `name = <value>  # comment`
// or `for name in <value>:`. Returns { line, from, to, text } or null.
function locate(param, doc) {
  const name = escapeRegExp(param.name);
  const assign = new RegExp(`^(${name}\\s*=\\s*)(.*?)\\s*(#.*)?$`);
  const loop = new RegExp(`^(\\s*for\\s+${name}\\s+in\\s+)(.*?)\\s*:\\s*(#.*)?$`);
  for (let i = 1; i <= doc.lines; i++) {
    const line = doc.line(i);
    const m = line.text.match(assign) ?? line.text.match(loop);
    if (m && m[2]) {
      const from = line.from + m[1].length;
      return { from, to: from + m[2].length, text: m[2] };
    }
  }
  return null;
}

// ------------------------------------------------------------ the widget --

const highlight = HighlightStyle.define([
  { tag: tags.keyword, color: "var(--py-keyword)", fontWeight: "600" },
  { tag: [tags.comment, tags.lineComment], color: "var(--py-comment)", fontStyle: "italic" },
  { tag: [tags.string, tags.special(tags.string)], color: "var(--py-string)" },
  { tag: [tags.number, tags.bool, tags.null], color: "var(--py-number)" },
  { tag: [tags.function(tags.definition(tags.variableName)), tags.function(tags.variableName)], color: "var(--py-function)" },
  { tag: [tags.operator, tags.punctuation], color: "var(--py-operator)" },
]);

class Exercise {
  constructor(root, base) {
    this.root = root;
    this.file = root.dataset.code;
    this.codeUrl = `${base}code/${this.file}`;
    this.outputUrl = `${base}code/output/${this.file.replace(/\.py$/, ".txt").replace(/^.*\//, "")}`;
    this.storageKey = this.file;
    this.running = false;
    this.queued = false;

    const spec = root.querySelector(".parameters");
    this.params = spec ? parseParameters(spec.textContent) : [];
    root.replaceChildren();
    root.classList.add("column-page");
  }

  async load() {
    const [code, booklet] = await Promise.all([
      fetch(this.codeUrl).then((r) => (r.ok ? r.text() : Promise.reject(r.statusText))),
      this.file.includes("/") ? null : fetch(this.outputUrl).then((r) => (r.ok ? r.text() : null)).catch(() => null),
    ]);
    this.original = code;
    this.booklet = booklet;

    let start = code;
    let note = "";
    const shared = location.hash.match(/^#code=(.+)$/);
    const saved = storage.get(this.storageKey);
    if (shared) {
      try {
        start = await decodeCode(shared[1]);
        note = "Code uit een gedeelde link.";
      } catch {}
    } else if (saved && saved.original === code && saved.code !== code) {
      start = saved.code;
      note = "Je eigen versie, bewaard in deze browser.";
    }

    this.build(start);
    this.setNote(note);
    runtime.listeners.add(this);
    this.pythonChanged();
  }

  build(code) {
    this.status = el("span", { class: "opgave-status", role: "status" });
    this.noteEl = el("span", { class: "opgave-note" });

    this.view = new EditorView({
      parent: (this.editorEl = el("div", { class: "opgave-editor" })),
      state: EditorState.create({
        doc: code,
        extensions: [
          lineNumbers(), highlightActiveLineGutter(), highlightActiveLine(), drawSelection(),
          history(), indentOnInput(), bracketMatching(), indentUnit.of("    "),
          python(), syntaxHighlighting(highlight), EditorView.lineWrapping,
          keymap.of([
            { key: "Mod-Enter", run: () => (this.run(), true) },
            { key: "Shift-Enter", run: () => (this.run(), true) },
            indentWithTab, ...defaultKeymap, ...historyKeymap,
          ]),
          EditorView.contentAttributes.of({ "aria-label": `Python-code ${this.file}` }),
          EditorView.updateListener.of((u) => u.docChanged && this.codeChanged(u)),
        ],
      }),
    });

    this.runButton = el("button", { class: "opgave-run", type: "button", onclick: () => this.toggleRun() });
    const resetButton = el("button", { type: "button", onclick: () => this.reset() }, "↺ Boekversie");
    const shareButton = el("button", { type: "button", onclick: () => this.share() }, "Link delen");
    const downloadButton = el("button", { type: "button", onclick: () => this.download() }, "Download .py");

    this.paramRows = this.params.map((p) => this.buildParam(p));
    this.output = el("pre", { class: "opgave-output", "aria-live": "polite" });
    this.outputHead = el("span", { class: "opgave-compare" });
    this.showPlaceholder();

    const left = el("div", { class: "opgave-left" },
      el("div", { class: "opgave-bar" }, el("span", { class: "opgave-file" }, this.file), this.status),
      this.editorEl,
      el("div", { class: "opgave-bar opgave-tools" }, this.noteEl, resetButton, shareButton, downloadButton),
    );
    const right = el("div", { class: "opgave-right" },
      this.params.length ? el("div", { class: "opgave-params" }, ...this.paramRows.map((r) => r.row)) : "",
      el("div", { class: "opgave-actions" }, this.runButton,
        el("span", { class: "opgave-hint" }, "of Ctrl+Enter in de code")),
      el("div", { class: "opgave-bar" }, el("span", { class: "opgave-label" }, "Uitvoer"), this.outputHead),
      this.output,
    );
    if (this.booklet !== null) {
      right.append(el("details", { class: "opgave-booklet" },
        el("summary", {}, "Uitvoer in het boekje"),
        el("pre", { class: "opgave-output" }, this.booklet)));
    }
    this.root.append(el("div", { class: "opgave-grid" }, left, right));
    this.syncParams();
    this.updateRunButton();
  }

  buildParam(param) {
    const value = el("output", { class: "param-value" });
    let input;
    if (param.type === "text") {
      input = el("input", { type: "text", spellcheck: "false", autocapitalize: "off", autocomplete: "off" });
      input.addEventListener("input", () => this.setParam(param, input.value.trim(), false));
      input.addEventListener("keydown", (e) => e.key === "Enter" && this.run());
    } else {
      const [min, max, step] = param.type === "range"
        ? [param.min, param.max, param.step]
        : [0, param.choices.length - 1, 1];
      input = el("input", { type: "range", min, max, step });
      input.addEventListener("input", () => {
        const text = param.type === "range"
          ? formatNumber(+input.value, param.decimals)
          : param.choices[+input.value];
        this.setParam(param, text, true);
      });
    }
    input.setAttribute("aria-label", param.name);
    const row = el("label", { class: `param param-${param.type}` },
      el("span", { class: "param-name" }, param.name),
      input,
      param.type === "text" ? "" : value,
      param.help ? el("span", { class: "param-help" }, param.help) : "",
    );
    return { param, row, input, value };
  }

  // Write a parameter value into the code. Sliders run the program right away.
  setParam(param, text, runNow) {
    const where = locate(param, this.view.state.doc);
    if (!text || !where || where.text === text) return;
    this.fromSlider = true;
    this.view.dispatch({ changes: { from: where.from, to: where.to, insert: text } });
    this.fromSlider = false;
    if (runNow) this.run();
  }

  // Code → sliders: show the value that is actually in the code.
  syncParams() {
    const doc = this.view.state.doc;
    for (const { param, row, input, value } of this.paramRows) {
      const where = locate(param, doc);
      row.classList.toggle("param-missing", !where);
      input.disabled = !where;
      row.title = where ? "" : `${param.name} staat niet (meer) in de code`;
      if (!where) continue;
      value.textContent = where.text;
      if (param.type === "text") {
        if (document.activeElement !== input) input.value = where.text;
      } else if (param.type === "range") {
        const number = Number(where.text);
        if (Number.isFinite(number)) input.value = number;
      } else {
        const exact = param.choices.indexOf(where.text);
        const index = exact >= 0 ? exact : param.choices.findIndex((c) => Number(c) === Number(where.text));
        if (index >= 0) input.value = index;
      }
    }
  }

  codeChanged(update) {
    this.syncParams();
    const code = update.state.doc.toString();
    if (code === this.original) storage.remove(this.storageKey);
    else storage.set(this.storageKey, { original: this.original, code });
    if (!this.fromSlider && location.hash.startsWith("#code=")) {
      window.history.replaceState(null, "", location.pathname + location.search);
    }
    this.setNote(code === this.original ? "" : "Je eigen versie, bewaard in deze browser.");
  }

  setNote(text) {
    this.noteEl.textContent = text;
  }

  pythonChanged(error) {
    if (error) {
      this.setStatus("error", "Python kon niet laden");
      this.write("err", `Python kon niet worden geladen (${error}).\nIs er internet? Herlaad de pagina om het opnieuw te proberen.\n`);
    } else if (this.running) {
      this.setStatus("busy", "Bezig…");
    } else if (runtime.ready) {
      this.setStatus("ready", `Python ${runtime.version}`);
      if (this.queued) {
        this.queued = false;
        this.run();
      }
    } else {
      this.setStatus("loading", "Python laden…");
    }
  }

  setStatus(state, text) {
    this.status.dataset.state = state;
    this.status.textContent = text;
  }

  updateRunButton() {
    this.runButton.textContent = this.running ? "■ Stop" : "▶ Uitvoeren";
    this.runButton.classList.toggle("is-running", this.running);
  }

  toggleRun() {
    if (this.running) this.stop("Gestopt.");
    else this.run();
  }

  run() {
    if (this.running || (runtime.owner && runtime.owner !== this)) {
      this.queued = true; // run again with the newest code when the current run ends
      return;
    }
    if (!runtime.ready) {
      this.queued = true;
      this.showPlaceholder("Python wordt nog geladen; de code start zodra het klaar is…");
      return;
    }
    const code = this.view.state.doc.toString();
    this.running = true;
    this.hadError = false;
    this.lines = 0;
    this.stdout = "";
    this.output.replaceChildren();
    this.outputHead.textContent = "";
    this.outputHead.className = "opgave-compare";
    this.updateRunButton();
    this.setStatus("busy", "Bezig…");

    runtime.owner = this;
    runtime.onMessage = (msg) => this.message(msg);
    runtime.worker.postMessage({ type: "run", code, filename: this.file.replace(/^.*\//, "") });
  }

  message(msg) {
    if (msg.type === "out" || msg.type === "err") {
      if (msg.type === "out") this.stdout += msg.text;
      else this.hadError = true;
      this.write(msg.type, msg.text);
      this.lines += (msg.text.match(/\n/g) ?? []).length;
      if (this.lines > MAX_LINES) {
        this.stop(`Gestopt: meer dan ${MAX_LINES} regels uitvoer. Zit er een oneindige lus in je code?`);
      }
    } else if (msg.type === "image") {
      this.output.append(el("img", { src: `data:image/png;base64,${msg.png}`, alt: "Grafiek gemaakt door de code" }));
    } else if (msg.type === "started") {
      // the time limit starts after packages such as matplotlib have loaded
      this.setStatus("busy", "Bezig…");
      this.timer = setTimeout(
        () => this.stop(`Gestopt na ${TIME_LIMIT_S} seconden. Zit er een oneindige lus in je code?`),
        TIME_LIMIT_S * 1000,
      );
    } else if (msg.type === "status") {
      this.setStatus("busy", /matplotlib|numpy|Loading/i.test(msg.text) ? "Pakketten laden…" : "Bezig…");
    } else if (msg.type === "done") {
      this.finish(msg);
    } else if (msg.type === "crash") {
      this.write("err", `Python is vastgelopen (${msg.message}).\n`);
      this.stop("Python wordt opnieuw gestart.");
    }
  }

  write(stream, text) {
    const last = this.output.lastChild;
    if (last && last.nodeName === "SPAN" && last.dataset.stream === stream) last.textContent += text;
    else this.output.append(el("span", { class: `out-${stream}`, "data-stream": stream }, text));
    this.output.scrollTop = this.output.scrollHeight;
  }

  finish({ ok, seconds: s }) {
    clearTimeout(this.timer);
    this.running = false;
    this.updateRunButton();
    if (!this.output.hasChildNodes()) this.write("note", "(de code heeft niets geprint)");
    let compare = `klaar in ${seconds(s)}`;
    if (ok && this.booklet !== null) {
      const same = sameText(this.stdout, this.booklet);
      compare += same ? " · ✓ zelfde als in het boekje" : " · anders dan in het boekje";
      this.outputHead.classList.toggle("is-same", same);
    }
    if (!ok) compare = "fout in de code ↓";
    this.outputHead.textContent = compare;
    this.outputHead.classList.toggle("is-error", !ok);
    this.release();
  }

  // Hand Python back; widgets with a queued run (e.g. a slider moved meanwhile) start it now.
  release() {
    runtime.owner = null;
    runtime.onMessage = null;
    runtime.notify();
  }

  stop(reason) {
    clearTimeout(this.timer);
    this.running = false;
    this.queued = false;
    this.write("note", `\n${reason}\n`);
    this.outputHead.textContent = "gestopt";
    this.outputHead.className = "opgave-compare is-error";
    this.updateRunButton();
    runtime.owner = null;
    runtime.onMessage = null;
    runtime.restart();
  }

  showPlaceholder(text = "Druk op ▶ Uitvoeren om de code te draaien.") {
    this.output.replaceChildren(el("span", { class: "out-note" }, text));
  }

  reset() {
    const code = this.view.state.doc.toString();
    if (code === this.original) return;
    if (!confirm("Je eigen wijzigingen weggooien en terug naar de code uit het boekje?")) return;
    this.view.dispatch({ changes: { from: 0, to: this.view.state.doc.length, insert: this.original } });
    this.showPlaceholder();
    this.outputHead.textContent = "";
  }

  async share() {
    const url = `${location.origin}${location.pathname}#code=${await encodeCode(this.view.state.doc.toString())}`;
    try {
      await navigator.clipboard.writeText(url);
      this.setNote("Link gekopieerd: wie hem opent, ziet jouw versie van de code.");
    } catch {
      prompt("Kopieer deze link:", url);
    }
  }

  download() {
    const blob = new Blob([this.view.state.doc.toString()], { type: "text/x-python" });
    const a = el("a", { href: URL.createObjectURL(blob), download: this.file.replace(/^.*\//, "") });
    a.click();
    setTimeout(() => URL.revokeObjectURL(a.href), 1000);
  }
}

export function init(base) {
  const roots = document.querySelectorAll(".opgave[data-code]");
  if (!roots.length) return;
  runtime.start();
  for (const root of roots) {
    new Exercise(root, base).load().catch((error) => {
      root.replaceChildren(el("p", { class: "opgave-failed" }, `Deze opgave kon niet worden geladen (${error}).`));
    });
  }
}
